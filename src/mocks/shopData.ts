/** Category list with accurate counts */
export function getCategoriesWithCounts(): ShopCategory[] {
  return SHOP_CATEGORIES.map(cat => ({
    ...cat,
    count: cat.id === 'all'
      ? SHOP_PRODUCTS.length
      : SHOP_PRODUCTS.filter(p => p.category === cat.id).length,
  }))
}

/** Find artisan by ID */
export function getArtisanById(id: string): ShopArtisan | undefined {
  return SHOP_ARTISANS.find(a => a.id === id)
}

/** Find product by slug */
export function getProductBySlug(slug: string): ShopProduct | undefined {
  return SHOP_PRODUCTS.find(p => p.slug === slug)
}
